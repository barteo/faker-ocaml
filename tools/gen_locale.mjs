// Generates the locale modules in lib/locales/ from the @faker-js/faker locale definitions:
//
//   <code>_data.ml          the raw definitions as a JSON string
//   locale_<code>.ml        the definition, its fallback chain and a prebuilt instance
//   faker_locales.ml        Faker.Locales: one module alias per locale (fakerDE, de, ...)
//   faker_all_locales.ml    Faker.All_locales: allLocales / allFakers (links every locale)
//
// Fallback chains are derived from the locale code (de_AT -> de -> en -> base) and checked
// against faker-js's own prebuilt instances, so they always match upstream.
//
// Usage: node tools/gen_locale.mjs [locale ...]   (default: every locale)
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { allFakers, allLocales, mergeLocales } from '@faker-js/faker';
import { chainOf } from './locale_chain.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'lib', 'locales');
const codes = Object.keys(allLocales);
const only = process.argv.slice(2);
for (const name of only) if (!allLocales[name]) throw new Error(`Unknown locale ${name}`);
const DELIM = 'fakerjson';
const HEADER = `(* GENERATED by tools/gen_locale.mjs from @faker-js/faker 10.6.0 - do not edit. *)\n\n`;

const capitalize = (s) => s[0].toUpperCase() + s.slice(1);
const moduleName = (code) => capitalize(code);

for (const code of codes) {
  const chain = chainOf(code);
  const merged = JSON.stringify(mergeLocales(chain.map((c) => allLocales[c])));
  if (merged !== JSON.stringify(allFakers[code].rawDefinitions))
    throw new Error(`fallback chain of ${code} doesn't match faker-js: ${chain.join(' -> ')}`);
}

for (const code of only.length ? only : codes) {
  const json = JSON.stringify(allLocales[code]);
  if (json.includes(`|${DELIM}}`)) throw new Error('delimiter collision');
  writeFileSync(join(dir, `${code}_data.ml`), `${HEADER}let json = {${DELIM}|${json}|${DELIM}}\n`);

  const chain = chainOf(code);
  const title = allLocales[code].metadata?.title ?? code;
  const out =
    HEADER +
    `(** The [${code}] locale (${title}). Fallback chain: ${chain.join(' -> ')}. *)\n\n` +
    `let def = lazy (Json.parse ${moduleName(code)}_data.json)\n\n` +
    `(** The raw [${code}] definitions, like faker-js [${code}]. *)\n` +
    `let definition () = Lazy.force def\n\n` +
    `(** The locale chain the prebuilt instance uses: ${chain.join(', ')}. *)\n` +
    `let chain () = [ ${chain.map((c) => (c === code ? 'definition ()' : `Locale_${c}.definition ()`)).join('; ')} ]\n\n` +
    `let instance = lazy (Core.create ~locale:(chain ()) ())\n\n` +
    `(** The shared [${code}] instance (random seed), like faker-js [faker${code.replace(/^[a-z]+/, (l) => l.toUpperCase())}]. *)\n` +
    `let faker () = Lazy.force instance\n`;
  writeFileSync(join(dir, `locale_${code}.ml`), out);
  console.log(`wrote ${code} (${json.length} bytes)`);
}

writeFileSync(
  join(dir, 'faker_locales.ml'),
  HEADER +
    `(* Module aliases only: a program links just the locales it uses. *)\n\n` +
    `let en () = Locale_en.definition ()\n` +
    `let base () = Locale_base.definition ()\n\n` +
    codes.map((c) => `module ${moduleName(c)} = Locale_${c}\n`).join(''),
);

const entries = (fn) => codes.map((c) => `    ("${c}", Locale_${c}.${fn});\n`).join('');
writeFileSync(
  join(dir, 'faker_all_locales.ml'),
  HEADER +
    `(* Referencing this module links every locale (like importing allFakers in faker-js). *)\n\n` +
    `(** Every locale definition by code, like faker-js [allLocales]. *)\n` +
    `let all_locales : (string * (unit -> Json.t)) list =\n  [\n${entries('definition')}  ]\n\n` +
    `(** Every locale's fallback chain by code. *)\n` +
    `let all_chains : (string * (unit -> Json.t list)) list =\n  [\n${entries('chain')}  ]\n\n` +
    `(** Every prebuilt instance by code, like faker-js [allFakers]. *)\n` +
    `let all_fakers : (string * (unit -> Core.t)) list =\n  [\n${entries('faker')}  ]\n\n` +
    `let find_chain code = Option.map (fun c -> c ()) (List.assoc_opt code all_chains)\n`,
);
console.log(`wrote faker_locales.ml and faker_all_locales.ml (${codes.length} locales)`);
