// Generates lib/internal/unicode_table.ml (NFKD) and lib/internal/unicode_case.ml (case mapping).
// unicode_table.ml: for code points whose NFKD form differs,
// the NFKD decomposition (as UTF-8). Covers the Latin, Greek, Cyrillic and
// compatibility blocks relevant to slugify()/internet usernames.
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const ranges = [[0x80, 0x52f], [0x1e00, 0x1fff], [0x2000, 0x218f], [0x2460, 0x24ff], [0x3000, 0x30ff], [0xfb00, 0xfb4f], [0xff00, 0xffef]];
const rows = [];
for (const [a, b] of ranges)
  for (let cp = a; cp <= b; cp++) {
    const s = String.fromCodePoint(cp);
    const d = s.normalize('NFKD');
    if (d !== s) rows.push(`  (0x${cp.toString(16)}, ${JSON.stringify(d).replace(/\\u([0-9a-f]{4})/g, (_, h) => `\\u{${h}}`)});`);
  }
writeFileSync(join(root, 'lib', 'internal', 'unicode_table.ml'),
  `(* GENERATED by tools/gen_unicode.mjs - do not edit. NFKD decompositions. *)\n\nlet nfkd = [|\n${rows.join('\n')}\n|]\n`);
console.log(rows.length);

// lib/internal/unicode_case.ml: String.prototype.toUpperCase/toLowerCase per code point, plus the
// Cased and Case_Ignorable ranges used by the final-sigma rule of toLowerCase.
const lit = (s) => JSON.stringify(s).replace(/\\u([0-9a-f]{4})/g, (_, h) => `\\u{${h}}`);
const upper = [];
const lower = [];
const prop = { cased: [], ignorable: [] };
const isCased = /^\p{Cased}$/u;
const isIgnorable = /^\p{Case_Ignorable}$/u;
for (let cp = 0; cp < 0x110000; cp++) {
  if (cp >= 0xd800 && cp <= 0xdfff) continue;
  const s = String.fromCodePoint(cp);
  if (s.toUpperCase() !== s) upper.push(`  (0x${cp.toString(16)}, ${lit(s.toUpperCase())});`);
  if (s.toLowerCase() !== s) lower.push(`  (0x${cp.toString(16)}, ${lit(s.toLowerCase())});`);
  for (const [k, re] of [['cased', isCased], ['ignorable', isIgnorable]]) {
    if (!re.test(s)) continue;
    const r = prop[k];
    if (r.length && r[r.length - 1][1] === cp - 1) r[r.length - 1][1] = cp;
    else r.push([cp, cp]);
  }
}
const rangeRows = (r) => r.map(([a, b]) => `  (0x${a.toString(16)}, 0x${b.toString(16)});`).join('\n');
writeFileSync(
  join(root, 'lib', 'internal', 'unicode_case.ml'),
  `(* GENERATED by tools/gen_unicode.mjs - do not edit. JS case mappings (node ${process.version}). *)\n\n` +
    `let upper = [|\n${upper.join('\n')}\n|]\n\nlet lower = [|\n${lower.join('\n')}\n|]\n\n` +
    `let cased = [|\n${rangeRows(prop.cased)}\n|]\n\nlet case_ignorable = [|\n${rangeRows(prop.ignorable)}\n|]\n`,
);
console.log(`case: ${upper.length} upper, ${lower.length} lower`);

// lib/internal/unicode_ccc.ml: the canonical ordering of combining marks that NFKD applies after
// decomposing. JS has no API for the canonical combining class, so marks are ranked by how
// normalize() orders them: NFD(a + b) is b + a exactly when ccc(a) > ccc(b) > 0.
{
  const nfd = (s) => s.normalize('NFD');
  const marks = [];
  for (let cp = 0; cp < 0x110000; cp++) {
    if (cp >= 0xd800 && cp <= 0xdfff) continue;
    const c = String.fromCodePoint(cp);
    if (c.normalize('NFKD') !== c) continue;
    // ccc > 1 sorts before U+0334 (ccc 1); 0 < ccc < 230 sorts after U+0301 (ccc 230);
    // ccc > 220 sorts before U+0316 (ccc 220).
    if (nfd(c + '̴') !== c + '̴' || nfd('́' + c) !== '́' + c || nfd(c + '̖') !== c + '̖')
      marks.push(c);
  }
  const cmp = (a, b) => (nfd(a + b) === b + a ? 1 : nfd(b + a) === a + b ? -1 : 0);
  marks.sort(cmp);
  const rows = [];
  let rank = 0;
  marks.forEach((m, i) => {
    if (i === 0 || cmp(marks[i - 1], m) !== 0) rank++;
    rows.push(`  (0x${m.codePointAt(0).toString(16)}, ${rank});`);
  });
  writeFileSync(
    join(root, 'lib', 'internal', 'unicode_ccc.ml'),
    `(* GENERATED by tools/gen_unicode.mjs - do not edit. Combining marks ranked by canonical\n` +
      `   combining class (node ${process.version}); unlisted code points are starters. *)\n\n` +
      `let rank = [|\n${rows.join('\n')}\n|]\n`,
  );
  console.log(`ccc: ${marks.length} marks in ${rank} classes`);
}
